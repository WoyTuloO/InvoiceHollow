    private void reloadChoiceCombo(){
        this.invoiceChoiceCombo.removeAllItems();
        this.invoiceChoiceCombo.addItem("");
        this.invoiceCollection.forEach((name,invoice)->{this.invoiceChoiceCombo.addItem(name);});
    }

